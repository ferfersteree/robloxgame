const {SP,T}=require('./lib.js');
const fs=require('fs');
const IDMAP={hazel_squirrel:'hazelnut_squirrel',sky_kitsune:'heavenly_kitsune'};
const RBH=JSON.parse(fs.readFileSync('rb_heights.json','utf8')); // roblox id -> height
const r3=x=>Math.round(x*1000)/1000;
const out={};
for(const jid of Object.keys(SP.pets)){
  const d=SP.pets[jid], rid=IDMAP[jid]||jid;
  const probe=new SP.u.Actor(d);probe.update(0);
  const jsH=probe.rig.bb.max.y-probe.rig.bb.min.y;
  const k=RBH[rid]/jsH;
  const rec={k:r3(k),rar:d.rar,hd:d.hd||2.6,rd:d.rd||1.1,landAt:d.landAt||.78,clearAt:d.clearAt||.42,fy:d.fy||0};
  const bake=(setup,dur)=>{
    const a=new SP.u.Actor(d);setup(a);a.update(0);
    const ch={y:[],x:[],z:[],rx:[],ry:[],rz:[],s:[]};const N=Math.round(dur*30);
    for(let i=0;i<=N;i++){
      if(i>0)a.update(1/30);
      const c=a.rig.acc.root;
      ch.x.push(r3(c.dp[0]*k));ch.y.push(r3(c.dp[1]*k));ch.z.push(r3(c.dp[2]*k));
      ch.rx.push(r3(c.dr[0]));ch.ry.push(r3(c.dr[1]));ch.rz.push(r3(c.dr[2]));
      ch.s.push(r3((c.ds[0]+c.ds[1]+c.ds[2])/3));
    }
    for(const key of Object.keys(ch)){const v=ch[key],neutral=key==='s'?1:0;if(v.every(q=>Math.abs(q-neutral)<1e-3))delete ch[key]}
    return ch;
  };
  rec.hatch=bake(a=>a.hatch(),rec.hd);
  rec.react=bake(a=>a.react(),rec.rd);
  out[rid]=rec;
}
fs.writeFileSync('baked.json',JSON.stringify(out));
// Lua
const lines=['--!nocheck','-- Generated by pets/tools bake: root-channel curves (30 Hz) of hatch/react from the Claude Design prototype.','-- k = studs per prototype unit. Channels: x,y,z offsets (studs), rx,ry,rz (radians), s uniform scale.','local D = {}'];
const arr=a=>'{'+a.join(',')+'}';
for(const id of Object.keys(out)){
  const r=out[id];
  let s=`D.${id} = { k=${r.k}, rar=${r.rar}, hd=${r.hd}, rd=${r.rd}, landAt=${r.landAt}, clearAt=${r.clearAt}, fy=${r.fy},`;
  for(const m of ['hatch','react']){s+=`\n ${m} = {`+Object.keys(r[m]).map(k=>`${k}=${arr(r[m][k])}`).join(', ')+'},'}
  s+='\n}';lines.push(s);
}
lines.push('return D');
fs.writeFileSync('PetAnimData.luau',lines.join('\n'));
console.log('baked',Object.keys(out).length,'bytes',lines.join('\n').length);
